"""Group eligibility failures by cause, fill failures.csv and write error_analysis.md.

  python scripts/error_groups.py --name a3_main

Reads runs/<name>/predictions.jsonl (latest record per run/model/system/pair) and runs/<name>/failures.csv.
Rules are keyword rules over the rule engine's own reasons, so the grouping is reproducible.
One failure can have several causes; counts are per cause.
"""
from __future__ import annotations

import argparse
import collections
import csv
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
TO_CODE = {"eligible": "E", "not_eligible": "NE", "insufficient_info": "II"}

S2_CAUSES = {
    "track": ("Alternative or track-specific requirements treated as all mandatory",
              "Add an applies-to-track field and any-of groups to the criteria schema; evaluate only the student's track"),
    "nationality": ("Nationality list misread",
                    "Keep the quote with every list; flag lists that exclude the user's country for curator review"),
    "grade_rule": ("Grade scales differ and no conversion rule extracted",
                   "Extract conversion tables into the grade rule; curator check when a rule is missing"),
    "missing_field": ("Extracted criterion missing a required field",
                      "Validate required fields per criterion type and retry extraction"),
    "age_date": ("Age limit without a reference date",
                 "Store each programme's deadline or intake date with the snapshot as the fallback"),
    "english": ("Missing English score labelled not eligible (guideline) vs insufficient (annotators)",
                "Clarify the English rule in the guideline and re-adjudicate affected pairs"),
    "other": ("Other single-criterion disagreement", "Review case by case on the development split"),
}
B1_FIX = "Move this decision to deterministic code (S2) or add the programme rule to the prompt context"


def s2_causes(r: dict) -> list[str]:
    want = {"NE": "not_eligible", "E": "eligible"}.get(r["pred"])
    crit = [c for c in r["criteria"]
            if (c["label"] == want if want else c["label"] not in ("eligible", "not_eligible", "manual_check"))]
    out = set()
    for c in crit:
        why = c.get("reason", "")
        if "vs 18 required" in why or ("degree in the profile" in why and why.startswith("No ")) \
                or "No degree found in the profile for this" in why:
            out.add("track")
        elif "reference date" in why:
            out.add("age_date")
        elif c["type"] == "nationality":
            out.add("nationality")
        elif "No accepted English" in why:
            out.add("english")
        elif "Scales differ" in why:
            out.add("grade_rule")
        elif "not stated" in why:
            out.add("missing_field")
        else:
            out.add("other")
    return sorted(out) or ["other"]


def b1_causes(r: dict) -> list[str]:
    out = set()
    for c in r["criteria"]:
        g = r["gold_types"].get(c["type"])
        if g and g != TO_CODE.get(c["label"], c["label"]):
            out.add(c["type"])
    return sorted(out) or ["overall only"]


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--name", default="a3_main")
    args = ap.parse_args()
    d = ROOT / "runs" / args.name
    latest = {}
    for line in open(d / "predictions.jsonl", encoding="utf-8"):
        r = json.loads(line)
        latest[(r["run"], r["model"], r["system"], r["pair_id"])] = r

    causes, counts = {}, collections.defaultdict(collections.Counter)
    for k, r in latest.items():
        if r["gold"] == r["pred"] or r.get("error"):
            continue
        sysm = (r["system"], r["model"])
        if r["system"] in ("S2", "S2-oracle"):
            cs = s2_causes(r)
            causes[k] = ("; ".join(S2_CAUSES[c][0] for c in cs), "; ".join(S2_CAUSES[c][1] for c in cs))
            for c in cs:
                counts[sysm][S2_CAUSES[c][0]] += 1
        elif r["system"] == "B1":
            cs = b1_causes(r)
            causes[k] = ("wrong criterion: " + ", ".join(cs), B1_FIX)
            for c in cs:
                counts[sysm][c] += 1

    fpath = d / "failures.csv"
    rows = list(csv.DictReader(open(fpath, encoding="utf-8")))
    for row in rows:
        for k, v in causes.items():
            if (k[1], k[2], k[3]) == (row["model"], row["system"], row["pair_id"]):
                row["final_cause"], row["planned_fix"] = v
    with open(fpath, "w", newline="", encoding="utf-8") as f:
        w = csv.DictWriter(f, fieldnames=list(rows[0].keys()))
        w.writeheader()
        w.writerows(rows)

    lines = [f"# Error analysis: {args.name}", "",
             "Generated by `python scripts/error_groups.py --name " + args.name + "` from predictions.jsonl.",
             "One failure can have several causes, so counts can sum to more than the number of failures.",
             "Fixes are for Assignment 4 and are checked on the development split only; nothing was changed",
             "after seeing these test results.", ""]
    for sysm in sorted(counts):
        n = sum(1 for k, r in latest.items() if (k[2], k[1]) == sysm and r["gold"] != r["pred"] and not r.get("error"))
        lines += [f"## {sysm[0]} / {sysm[1]}: {n} failures", "", "| Cause | Failures | Planned fix |", "| --- | --- | --- |"]
        fixes = {v[0]: v[1] for v in S2_CAUSES.values()}
        for cause, c in counts[sysm].most_common():
            lines.append(f"| {cause} | {c} | {fixes.get(cause, B1_FIX)} |")
        lines.append("")
    (d / "error_analysis.md").write_text("\n".join(lines), encoding="utf-8")
    print("\n".join(lines))


if __name__ == "__main__":
    main()